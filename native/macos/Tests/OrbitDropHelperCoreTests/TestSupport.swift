/// IEEE-754 bit pattern written as 16 hex digits (fixtures generated by scripts/gen-fixtures.mjs).
func double(fromBits hex: String) -> Double {
  Double(bitPattern: UInt64(hex, radix: 16)!)
}

func bits(_ value: Double) -> String {
  let raw = String(value.bitPattern, radix: 16)
  return String(repeating: "0", count: 16 - raw.count) + raw
}

/// Deterministic session ids for controller tests.
final class Counter: @unchecked Sendable {
  private var value = 0
  func next() -> String {
    value += 1
    return "s\(value)"
  }
}

extension HelperToMainMessage {
  /// Decoded JSON object of the encoded line (for structural assertions).
  func jsonObject() throws -> [String: Any] {
    let data = try NDJSON.encodeLine(self)
    XCTAssertEqual(data.last, 0x0A)
    return try JSONSerialization.jsonObject(with: data.dropLast()) as! [String: Any]
  }
}
